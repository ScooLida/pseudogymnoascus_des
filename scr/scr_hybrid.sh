Шаг 1: Подготовка «гибридного» референса
Главная хитрость — объединить два родительских генома в один файл, но обязательно переименовать хромосомы, чтобы они не конфликтовали.

Возьми файл ParentA.fasta и ParentB.fasta.

Добавь префиксы к названиям последовательностей (например, через sed или простой скрипт):

Вместо >chrM сделай >Mother_chrM и >Father_chrM.

Склей их в один файл:

Bash

cat Mother_modified.fasta Father_modified.fasta > Combined_Ref.fasta
Шаг 2: Индексация
Создай индекс для этого объединенного файла. Индексатор (например, BWA или Bowtie2) будет воспринимать это как один огромный геном, состоящий из двух очень похожих частей.

Bash

bwa index Combined_Ref.fasta
Шаг 3: Картирование
Запускай выравнивание своих данных (ридов из дочерней клетки/зиготы) на этот комбинированный референс.

Bash

bwa mem -t 8 Combined_Ref.fasta reads_R1.fastq reads_R2.fastq > output.sam
Что происходит в этот момент внутри алгоритма?
Когда рид «видит» два почти идентичных участка (отцовский и материнский), он сравнивает Alignment Score (AS). Если в отцовском варианте есть хоть одна мутация, которая совпадает с ридом, а в материнском — нет, рид получит более высокий балл за «отцовскую» сторону и прикрепится туда.

Шаг 4: Фильтрация и разбор «ничьей»
Здесь начинается самое важное. Если участок ДНК у родителей абсолютно одинаковый, риду всё равно, куда садиться.

Такие риды получат Mapping Quality (MAPQ) = 0 или очень низкий балл, потому что алгоритм не уверен в их уникальности.

Для точного анализа гетероплазмии нам нужны только «уникально определившиеся» риды.

Используй samtools для разделения:

Отцовские риды: те, что сели на хромосомы с префиксом Father_ с высоким качеством (например, -q 20).

Материнские риды: те, что сели на Mother_ с тем же качеством.

Bash

# Вытаскиваем только те, что сели на материнский геном
samtools view -b -q 20 output.bam Mother_chrM > maternal_only.bam
Шаг 5: Подсчет статистики
Теперь у тебя есть два файла. Количество ридов в каждом из них — это и есть пропорция отцовского и материнского вклада.

Если maternal_only.bam содержит 80 000 ридов, а paternal_only.bam — 20 000, то уровень гетероплазмии по отцу — 20%.
